    internal static BidiClass Get(int codePoint)
    {
        var low = 0;
        var high = Starts.Length - 1;
        while (low <= high)
        {
            var middle = low + ((high - low) >> 1);
            if (codePoint < Starts[middle])
            {
                high = middle - 1;
            }
            else if (codePoint > Ends[middle])
            {
                low = middle + 1;
            }
            else
            {
                return (BidiClass)Classes[middle];
            }
        }

        return BidiClass.L;
    }

    internal static bool TryGetPairedBracket(int codePoint, out int pair)
        => TryGetPairedBracketInfo(codePoint, out pair, out _);

    internal static bool TryGetPairedBracketInfo(int codePoint, out int pair, out bool isOpening)
    {
        var low = 0;
        var high = BracketCodePoints.Length - 1;
        while (low <= high)
        {
            var middle = low + ((high - low) >> 1);
            if (codePoint < BracketCodePoints[middle])
            {
                high = middle - 1;
            }
            else if (codePoint > BracketCodePoints[middle])
            {
                low = middle + 1;
            }
            else
            {
                pair = checked((int)PairedWith[middle]);
                isOpening = (middle & 1) == 0;
                return true;
            }
        }

        pair = 0;
        isOpening = false;
        return false;
    }
